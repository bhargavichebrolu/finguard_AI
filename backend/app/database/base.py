"""The declarative base and shared column helpers for all SQLAlchemy models."""

import enum
import uuid
from datetime import datetime

from sqlalchemy import DateTime, Enum, MetaData, Uuid, func
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

# Predictable constraint names let Alembic find and change them later.
NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    """The parent of every table class."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)


def enum_type(enum_class: type[enum.Enum], name: str) -> Enum:
    """Store an enum's values as text with a CHECK constraint, which is simple to extend."""
    return Enum(
        enum_class,
        name=name,
        native_enum=False,
        create_constraint=True,
        length=32,
        values_callable=lambda members: [member.value for member in members],
    )


def uuid_primary_key() -> Mapped[uuid.UUID]:
    """Return a primary key generated by the application, so it is known before the insert."""
    return mapped_column(Uuid, primary_key=True, default=uuid.uuid4)


def created_at_column() -> Mapped[datetime]:
    """Return a timestamp set by the database, so all records share one clock."""
    return mapped_column(DateTime(timezone=True), server_default=func.now(), nullable=False)
